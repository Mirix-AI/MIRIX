-- Migration: procedural_memory retrieval fields.
--
-- Run once on existing PostgreSQL databases, AFTER scripts/migrate_procedural_to_skill.sql
-- (it needs the skill columns name / triggers / description). New databases get
-- this schema via SQLAlchemy create_all (mirix/orm/procedural_memory.py).
--
-- Steps:
--   1. description_embedding -> retrieval_embedding (rename). A skill now has ONE
--      vector: the embedding of its retrieval text (name + triggers +
--      description). The renamed column is CLEARED in the same step because the
--      old vectors embedded `description` alone. Rows with a NULL
--      retrieval_embedding are re-embedded by the server's startup backfill and
--      by scripts/reembed_skill_retrieval.py;
--      until then those skills are served by keyword search only.
--   2. DROP instructions_embedding: instructions carry no vector any more; an
--      embedding search on `instructions` runs as full-text search.
--   3. ADD the generated keyword document retrieval_tsv (name and triggers at
--      weight A, description at weight B) + its GIN index, for BM25 ranking.
--      The expression is identical to RETRIEVAL_TSV_EXPRESSION in
--      mirix/orm/procedural_memory.py. It indexes `triggers::jsonb::text`:
--      the text of a JSON column is the stored json.dumps output, whose
--      \uXXXX escapes turned the words next to a curly quote, a dash or any
--      non-ASCII character into lexemes like 'u201ccool'; the JSONB cast
--      decodes them (a no-op when triggers is JSONB). jsonb's own text still
--      escapes control characters, quotes and backslashes (a trigger
--      "line1<newline>line2" is ["line1\nline2"], parsed as 'nline2'):
--      regexp_replace turns every such escape into a space first. A
--      retrieval_tsv built by an earlier expression (`triggers::text`, or
--      `triggers::jsonb::text` without the regexp_replace) is dropped and
--      added again, once (its GIN index goes with it and is recreated below).
--      Adding a STORED generated column rewrites the table once (brief ACCESS
--      EXCLUSIVE lock); skill tables are small.
--   4. Replace the full UNIQUE (organization_id, user_id, name) constraint with a
--      PARTIAL unique index over live rows (WHERE NOT is_deleted), so a
--      soft-deleted skill no longer blocks re-creating its name.
--
-- Idempotent: the rename (and the clear) only happen while description_embedding
-- still exists and retrieval_embedding does not, so a re-run never wipes vectors
-- that were recomputed in between; everything else is IF [NOT] EXISTS / guarded.
--
-- NOT safe for a rolling deploy: unlike the other scripts of this set it is
-- destructive (it renames, clears and drops columns the previous server version
-- reads and writes). Stop every old MIRIX server process first, run this
-- script, then start the new version — an old server still running would fail
-- every procedural-memory read and write with UndefinedColumn.

BEGIN;

-- Step 1: rename + clear, exactly once.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'procedural_memory'
          AND column_name = 'description_embedding'
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'procedural_memory'
          AND column_name = 'retrieval_embedding'
    ) THEN
        ALTER TABLE procedural_memory RENAME COLUMN description_embedding TO retrieval_embedding;
        UPDATE procedural_memory SET retrieval_embedding = NULL;
    END IF;
END$$;

-- Databases that somehow have neither column get an empty one; databases that
-- somehow have both keep retrieval_embedding and drop the stale description one.
ALTER TABLE procedural_memory ADD COLUMN IF NOT EXISTS retrieval_embedding vector(4096) NULL;
ALTER TABLE procedural_memory DROP COLUMN IF EXISTS description_embedding;

-- Step 2.
ALTER TABLE procedural_memory DROP COLUMN IF EXISTS instructions_embedding;

-- Step 3. A retrieval_tsv generated by an earlier version of this script
-- indexes JSON escapes instead of words: `triggers::text` on a JSON column
-- (\uXXXX of every non-ASCII character), `triggers::jsonb::text` on either
-- column type (\n, \t, \" ... of control characters and quotes). Rebuild it,
-- once: the current expression is the only one with regexp_replace, so a
-- re-run finds it and leaves it alone (no table rewrite per run).
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_attribute a
        JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = 'procedural_memory'::regclass
          AND a.attname = 'retrieval_tsv'
          AND NOT a.attisdropped
          AND pg_get_expr(d.adbin, d.adrelid) NOT LIKE '%regexp_replace%'
    ) THEN
        ALTER TABLE procedural_memory DROP COLUMN IF EXISTS retrieval_tsv;
    END IF;
END$$;

ALTER TABLE procedural_memory
    ADD COLUMN IF NOT EXISTS retrieval_tsv tsvector GENERATED ALWAYS AS (
        setweight(to_tsvector('english', coalesce(name, '')), 'A') ||
        setweight(to_tsvector('english', coalesce(regexp_replace(triggers::jsonb::text, '\\(["\\/bfnrt]|u[0-9a-fA-F]{4})', ' ', 'g'), '')), 'A') ||
        setweight(to_tsvector('english', coalesce(description, '')), 'B')
    ) STORED;

CREATE INDEX IF NOT EXISTS ix_procedural_memory_retrieval_tsv
    ON procedural_memory USING gin (retrieval_tsv);

-- Step 4. The old constraint cannot hold a duplicate among live rows, so the
-- partial index always builds.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uq_procedural_memory_org_user_name'
          AND conrelid = 'procedural_memory'::regclass
    ) THEN
        ALTER TABLE procedural_memory DROP CONSTRAINT uq_procedural_memory_org_user_name;
    END IF;
END$$;
-- In case it was ever created as a plain unique index rather than a constraint.
DROP INDEX IF EXISTS uq_procedural_memory_org_user_name;

CREATE UNIQUE INDEX IF NOT EXISTS uq_procedural_memory_org_user_name_active
    ON procedural_memory (organization_id, user_id, name)
    WHERE NOT is_deleted;

COMMIT;
